PRELUDE = """
#ifndef C12_LXR_IN_RAM
#define C12_LXR_IN_RAM %(in_ram)d
#endif
#if C12_LXR_IN_RAM && !defined(WASM) && !defined(EMU)
// The LXR's per-sample code (the firmware's IN_ITCM_RAM functions) in SRAM, through the same
// section family PLINKY_DSP_RAM_FUNC uses. Off by default: the RAM code region is small. Each
// function gets a section of its own (GCC 13 refuses inline and out-of-line functions in one), and
// is never cloned (-O3's clones of a function would share its section, which GCC also refuses).
#define C12_STR2_(x) #x
#define C12_STR_(x) C12_STR2_(x)
#define C12_LXR_CODE __attribute__((noinline, noclone, section(".time_critical.c12lxr." C12_STR_(__COUNTER__))))
#else
#define C12_LXR_CODE
#endif
#define C12_LXR_DATA
// The engine's working memory (39 KB) is a member of the panel object, in Plinky's 128 KB panel
// arena, not static SRAM (tools/amalgamate.py, RELOCATE).
#define C12_ENGINE_RAM_EXTERNAL 1
"""


def strip_comments(text):
    """C++ comments out, string and character literals untouched (the glue has no raw strings)."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            out.append(" ")
            i = n if j < 0 else j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def bytes_literal(vals):
    """A C string literal (split into lines of adjacent literals) whose bytes are vals: printable
    characters as themselves, the rest as octal escapes ('?' too, so no trigraph can form)."""
    out, line = [], ""
    for i, v in enumerate(vals):
        c = chr(v)
        if 0x20 <= v < 0x7f and c not in "\\\"?":
            esc = c
        else:
            nxt = vals[i + 1] if i + 1 < len(vals) else None
            # an octal escape takes up to three digits: pad it when a digit follows
            esc = "\\%o" % v if nxt is None or not (0x30 <= nxt <= 0x37) else "\\%03o" % v
        line += esc
        if len(line) >= 160:
            out.append('"%s"' % line)
            line = ""
    if line:
        out.append('"%s"' % line)
    return "\n".join(out)


def shrink_engine(text):
    """Size only, the same program: CLATTER Pocket's packed LXR tables (byte arrays of fixed size,
    read through their own length fields, never with sizeof) as string literals, one byte longer
    for the terminating zero; and the parameter table's offset expressions through two macros."""
    n_tables = 0

    def table(m):
        nonlocal n_tables
        vals = [int(v) for v in m.group(3).replace("\n", " ").split(",") if v.strip()]
        if len(vals) != int(m.group(2)) or any(v < 0 or v > 255 for v in vals):
            sys.exit("make_panel: %s is not a byte table of %s" % (m.group(1), m.group(2)))
        n_tables += 1
        return "static const uint8_t %s[%d] =\n%s;" % (m.group(1), len(vals) + 1, bytes_literal(vals))
    text = re.sub(r"static const uint8_t (\w+_data)\[(\d+)\] = \{([\d,\s]+)\};", table, text)
    if n_tables != 5:
        sys.exit("make_panel: expected the 5 packed LXR tables, found %d" % n_tables)
    m = re.search(r"static const struct place places\[END_OF_SOUND_PARAMETERS\] = \{.*?\};", text, re.S)
    if not m:
        sys.exit("make_panel: the parameter places table was not found")
    body = m.group(0)
    body, a = re.subn(r"\(\(uint16_t\)\(\((\d+)\) \* sizeof\((\w+)\[0\]\) \+ __builtin_offsetof\(__typeof__\(\2\[0\]\), ([\w.\[\]]+)\)\)\)",
                      r"C12PA(\2,\1,\3)", body)
    body, b = re.subn(r"\(uint16_t\)__builtin_offsetof\(__typeof__\((\w+)\), ([\w.\[\]]+)\)", r"C12PO(\1,\2)", body)
    if a < 50 or b < 20:
        sys.exit("make_panel: the places table did not take its macros (%d, %d)" % (a, b))
    macros = ("#define C12PA(o,i,m) ((uint16_t)((i) * sizeof(o[0]) + __builtin_offsetof(__typeof__(o[0]), m)))\n"
              "#define C12PO(o,m) (uint16_t)__builtin_offsetof(__typeof__(o), m)\n")
    text = text[:m.start()] + macros + body + "\n#undef C12PA\n#undef C12PO" + text[m.end():]
    return text


def compact(text):
    out = []
    for line in text.split("\n"):
        s = line.strip()
        if not s:
            continue
        s = re.sub(r"[ \t]+", " ", s) if '"' not in s and "'" not in s else s
        out.append(s)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", default=os.path.join(ROOT, "build", "c12_engine.inc"))
    ap.add_argument("--glue", default=os.path.join(ROOT, "panel", "clatter12.cpp"))
    ap.add_argument("--compact", action="store_true")
    ap.add_argument("--in-ram", type=int, default=0)
    ap.add_argument("--extra", default="", help="extra #defines, e.g. 'C12_PERF_LOG 0'")
    ap.add_argument("-o", dest="out", default=os.path.join(ROOT, "build", "clatter_12.cpp"))
    a = ap.parse_args()

    version = open(os.path.join(ROOT, "VERSION")).read().strip() if os.path.exists(
        os.path.join(ROOT, "VERSION")) else "0.0.0"
    commit = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short=12", "HEAD"], capture_output=True,
                            text=True).stdout.strip() or "uncommitted"
    dirty = subprocess.run(["git", "-C", ROOT, "status", "--porcelain", "--untracked-files=no"],
                           capture_output=True, text=True).stdout.strip()
    if dirty:
        commit += "+modified"
    tables = "static SRAM" if re.search(r"C12_TABLES_IN_PSRAM\s+0", a.extra) else "PSRAM"
    config = "LXR tables in %s, LXR code in %s, %s" % (tables, "SRAM" if a.in_ram else "flash",
                                                       "compact" if a.compact else "full")

    engine = open(a.engine).read()
    if a.compact:
        engine = compact(shrink_engine(engine))
    glue = open(a.glue).read()
    if a.compact:
        # the glue's comments are for reading the source (panel/clatter12.cpp, and _full.cpp)
        glue = compact(strip_comments(glue))
    extra = "".join("#define %s\n" % d.strip() for d in a.extra.split(",") if d.strip())

    with open(a.out, "w") as f:
        f.write(METADATA % {"version": version, "commit": commit, "config": config})
        f.write(NOTICE)
        f.write(extra)
        f.write(PRELUDE % {"in_ram": a.in_ram})
        f.write(engine)
        f.write(glue)
    size = os.path.getsize(a.out)
    print("make_panel: %s, %d bytes (%.0f KB)" % (os.path.relpath(a.out, ROOT), size, size / 1024.0))


if __name__ == "__main__":
    main()

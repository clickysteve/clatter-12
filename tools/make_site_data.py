#!/usr/bin/env python3
"""make_site_data.py - assemble docs/assets/data.js and the audio clips for the project page.

Copyright (C) 2026 The CLATTER contributors. SPDX-License-Identifier: GPL-3.0-only

Inputs (made by `make site-data`): build/patterns.bin + build/patterns_meta.json from
tools/export_patterns.c (CLATTER Pocket's generator, real output) and build/clips/*.wav +
build/clips_meta.json from tools/render_clips.c (CLATTER 12's engine, rendered on a desktop).
Writes the patterns (base64), style and kit names, and for each clip a 96-bar waveform and its MP3."""
import base64, json, os, shutil, struct, subprocess, sys, wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = os.path.join(ROOT, "build")
OUT = os.path.join(ROOT, "docs", "assets")
meta = json.load(open(os.path.join(B, "patterns_meta.json")))
clips = json.load(open(os.path.join(B, "clips_meta.json")))
pat = open(os.path.join(B, "patterns.bin"), "rb").read()
expect = len(meta["styles"]) * meta["seeds"] * meta["chain"] * meta["tracks"] * meta["steps"] * 2
assert len(pat) == expect, (len(pat), expect)

os.makedirs(os.path.join(OUT, "audio"), exist_ok=True)
for c in clips:
    w = wave.open(os.path.join(B, "clips", c["file"] + ".wav"))
    raw = w.readframes(w.getnframes())
    a = struct.unpack("<%dh" % (len(raw) // 2), raw)
    n = len(a) // 2
    bars = 96
    pk = []
    for i in range(bars):
        seg = a[2 * (i * n // bars): 2 * ((i + 1) * n // bars)]
        pk.append(max(abs(x) for x in seg) if seg else 0)
    top = max(pk) or 1
    c["peaks"] = [round(p / top, 2) for p in pk]
    c["title"] = "%s × %s" % (meta["styles"][c["style"]], meta["kits"][c["kit"]])
    mp3 = os.path.join(OUT, "audio", c["file"] + ".mp3")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", os.path.join(B, "clips", c["file"] + ".wav"),
                    "-codec:a", "libmp3lame", "-b:a", "96k", "-metadata", "title=CLATTER 12: " + c["title"],
                    "-metadata", "comment=Rendered on a desktop by CLATTER 12's engine; not a Plinky recording", mp3], check=True)
    c["bytes"] = os.path.getsize(mp3)

data = dict(meta, patterns=base64.b64encode(pat).decode("ascii"), clips=clips)
with open(os.path.join(OUT, "data.js"), "w") as f:
    f.write("/* Generated by tools/make_site_data.py from CLATTER's own generator and engine. Do not edit. */\n")
    f.write("window.C12DATA=" + json.dumps(data, separators=(",", ":")) + ";\n")
print("make_site_data: data.js %d bytes, %d patterns, %d clips" % (os.path.getsize(os.path.join(OUT, "data.js")),
      len(pat) // (meta["tracks"] * meta["steps"] * 2), len(clips)))
